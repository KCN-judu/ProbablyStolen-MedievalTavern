ADVANCE: Final = 6      # a 5 pixel glyph and one pixel of space


def width(text: str, scale: int = 1) -> int:
    """The width in pixels of a line of text."""
    return max(0, (len(text) * ADVANCE - 1) * scale)


def write(p: Pix, x: int, y: int, text: str, c: Color, scale: int = 1) -> int:
    """Paints `text` with its top left corner at (x, y). Returns the x after the last glyph. A character the alphabet
    does not have is skipped, so a caller never fails on lettering."""
    for ch in text.upper():
        rows = GLYPHS.get(ch)
        if rows is not None:
            for j, row in enumerate(rows):
                for i, bit in enumerate(row):
                    if bit == "1":
                        p.rect(x + i * scale, y + j * scale, scale, scale, c)
        x += ADVANCE * scale
    return x
