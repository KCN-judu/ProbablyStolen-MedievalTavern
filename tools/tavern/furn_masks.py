def mask(key: str, w: int) -> Image.Image:
    """The occupied area as an L mask (255 inside)."""
    rows = RUNS[key]
    m = Image.new("L", (w, len(rows)), 0)
    for y, row in enumerate(rows):
        for x0, x1 in row:
            m.paste(255, (x0, y, x1, y + 1))
    return m
